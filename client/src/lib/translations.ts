// Merge all COMMON_PHRASES directly into TRANSLATIONS for instant direct lookup
export const LOWERCASE_PHRASES: Record<string, Record<Language, string>> = {};
Object.keys(COMMON_PHRASES).forEach((phrase) => {
  const p = COMMON_PHRASES[phrase];
  TRANSLATIONS.en[phrase] = p.en;
  TRANSLATIONS.am[phrase] = p.am;
  TRANSLATIONS.om[phrase] = p.om;
  TRANSLATIONS.ti[phrase] = p.ti;
  LOWERCASE_PHRASES[phrase.toLowerCase()] = p;
});

/**
 * Direct lookup function that safely translates any text or key into the target language.
 */
export function translateText(text: string, lang: Language): string {
  if (!text || lang === "en") return text;
  const trimmed = text.trim();
  const dict = TRANSLATIONS[lang];
  if (dict && dict[trimmed]) {
    return dict[trimmed];
  }
  const phrase = COMMON_PHRASES[trimmed];
  if (phrase && phrase[lang]) {
    return phrase[lang];
  }
  return text;
}
